#!/usr/bin/env node
/**
 * Download Verbandsliga Süd crests from TFVH into public/crests/
 * and regenerate src/lib/tfvh/crests.generated.ts
 *
 * Usage: pnpm sync:crests
 */
import { createWriteStream } from "node:fs";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { pipeline } from "node:stream/promises";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = path.join(ROOT, "public", "crests");
const GENERATED = path.join(ROOT, "src", "lib", "tfvh", "crests.generated.ts");
const LEAGUE_URL = "https://tfvh.de/index.php/verbandsliga-sued";
const HEADERS = {
  "User-Agent": "TFCFlorstadtOverlay/0.1 (+https://tfc-florstadt.de)",
  Accept: "text/html,image/*",
};

const TEAM_ROW_RE =
  /<a href="\/index\.php\/verbandsliga-sued\?task=team_details&id=(\d+)">([^<]+)<\/a>[\s\S]*?(?:<img src="(https:\/\/tfvh\.de\/images\/sportsmanager\/vereine\/[^"]+)"|<\/tr>)/gi;

function decodeEntities(value) {
  return value
    .replace(/&uuml;/gi, "ü")
    .replace(/&Uuml;/gi, "Ü")
    .replace(/&auml;/gi, "ä")
    .replace(/&Auml;/gi, "Ä")
    .replace(/&ouml;/gi, "ö")
    .replace(/&Ouml;/gi, "Ö")
    .replace(/&szlig;/gi, "ß")
    .replace(/&amp;/gi, "&")
    .replace(/&nbsp;/gi, " ")
    .trim();
}

function toHiRes(url) {
  return url.replace(/W\d+H\d+/i, "W240H240");
}

function sourceKey(url) {
  const m = url.match(/\/(I\d+T\d+)/i);
  return m?.[1] ?? null;
}

function parseTeams(html) {
  const teams = [];
  const seen = new Set();
  TEAM_ROW_RE.lastIndex = 0;
  let match = TEAM_ROW_RE.exec(html);
  while (match) {
    const id = match[1];
    const name = decodeEntities(match[2]);
    const thumb = match[3] ?? null;
    if (id && name && !seen.has(id)) {
      seen.add(id);
      teams.push({
        id,
        name,
        remoteUrl: thumb ? toHiRes(thumb) : null,
      });
    }
    match = TEAM_ROW_RE.exec(html);
  }
  return teams;
}

async function enrichFromDetails(team) {
  if (!team.remoteUrl) return team;
  try {
    const res = await fetch(
      `${LEAGUE_URL}?task=team_details&id=${encodeURIComponent(team.id)}`,
      { headers: HEADERS },
    );
    if (!res.ok) return team;
    const html = await res.text();
    const m = html.match(
      /src="(https:\/\/tfvh\.de\/images\/sportsmanager\/vereine\/[^"]+W240H240\.[a-zA-Z]+)"/i,
    );
    if (m?.[1]) return { ...team, remoteUrl: m[1] };
  } catch {
    // keep table-derived URL
  }
  return team;
}

async function download(url, dest) {
  const res = await fetch(url, { headers: HEADERS });
  if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
  if (!res.body) throw new Error(`No body for ${url}`);
  await pipeline(res.body, createWriteStream(dest));
}

async function main() {
  console.log("Fetching", LEAGUE_URL);
  const leagueRes = await fetch(LEAGUE_URL, { headers: HEADERS });
  if (!leagueRes.ok) {
    throw new Error(`League page HTTP ${leagueRes.status}`);
  }
  let teams = parseTeams(await leagueRes.text());
  if (teams.length === 0) throw new Error("No teams parsed");

  console.log(`Found ${teams.length} teams — enriching logos…`);
  teams = await Promise.all(teams.map(enrichFromDetails));

  await mkdir(OUT_DIR, { recursive: true });

  /** @type {Record<string, string>} */
  const byTeamId = {};
  /** @type {Record<string, string>} */
  const bySourceKey = {};
  /** @type {{ id: string; name: string; logoUrl: string }[]} */
  const fallback = [];

  for (const team of teams) {
    if (!team.remoteUrl) {
      console.warn(`  skip ${team.name} (${team.id}): no logo URL`);
      continue;
    }
    const ext = path.extname(new URL(team.remoteUrl).pathname).toLowerCase() || ".jpg";
    const fileName = `${team.id}${ext}`;
    const dest = path.join(OUT_DIR, fileName);
    const localPath = `/crests/${fileName}`;
    process.stdout.write(`  ${team.name} → ${fileName} … `);
    try {
      await download(team.remoteUrl, dest);
      console.log("ok");
      byTeamId[team.id] = localPath;
      const key = sourceKey(team.remoteUrl);
      if (key) bySourceKey[key] = localPath;
      fallback.push({ id: team.id, name: team.name, logoUrl: localPath });
    } catch (err) {
      console.log("FAIL");
      console.warn(`    ${err instanceof Error ? err.message : err}`);
    }
  }

  const generated = `/* eslint-disable */
// AUTO-GENERATED by scripts/sync-tfvh-crests.mjs — do not edit by hand.
// Run: pnpm sync:crests

export const LOCAL_CRESTS_BY_TEAM_ID: Record<string, string> = ${JSON.stringify(byTeamId, null, 2)};

export const LOCAL_CRESTS_BY_SOURCE_KEY: Record<string, string> = ${JSON.stringify(bySourceKey, null, 2)};

export const LEAGUE_TEAMS_LOCAL: { id: string; name: string; logoUrl: string }[] = ${JSON.stringify(fallback, null, 2)};
`;

  await writeFile(GENERATED, `${generated}\n`, "utf8");
  console.log(`Wrote ${GENERATED}`);
  console.log(`Crests in ${OUT_DIR} (${Object.keys(byTeamId).length} files)`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
